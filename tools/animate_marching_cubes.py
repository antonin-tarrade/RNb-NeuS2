#  loading + ExternalMethod.get_density — kept standalone here on purpose)
# ════════════════════════════════════════════════════════════════════════

def load_testbed(snapshot_path):
    try:
        import pyngp as ngp
    except ImportError:
        print("Error: pyngp not found. Run this on the machine/env with "
              "your NeuS2 build.")
        sys.exit(1)
    testbed = ngp.Testbed(ngp.TestbedMode.Nerf)
    if not os.path.exists(snapshot_path):
        print(f"Error: snapshot {snapshot_path} not found.")
        sys.exit(1)
    print(f"Loading snapshot from {snapshot_path}...")
    testbed.load_snapshot(snapshot_path)
    return testbed


def get_sdf_grid(testbed, resolution):
    """Returns an (res,res,res) array indexed [x, y, z], i.e. grid[i,j,k]
    matches the corner/edge convention the lookup table assumes."""
    aabb = testbed.render_aabb
    raw = testbed.get_density_grid(resolution, resolution, resolution, aabb)
    # testbed stores density as [Z, Y, X]; transpose to [X, Y, Z]
    # (same transpose your PyMCubes extractor applies before calling mcubes)
    grid = np.transpose(np.asarray(raw), (2, 1, 0))
    return grid


# ════════════════════════════════════════════════════════════════════════
#  Cube-by-cube marching cubes + animation
# ════════════════════════════════════════════════════════════════════════

def run_animation(grid, out_video, fps, empty_stride, hold_frames,
                   rotate_per_frame, figsize, dpi, threshold=0.0,
                   surface_stride=1, final_spin_seconds=4.0):
    N = grid.shape[0]
    verts = []
    faces = []
    frame_writer = imageio.get_writer(out_video, fps=fps, codec="libx264", quality=8)

    fig = plt.figure(figsize=figsize, dpi=dpi)
    fig.patch.set_facecolor(BG_COLOR)
    ax = fig.add_subplot(111, projection="3d")
    fig.subplots_adjust(left=0, right=1, bottom=0, top=1)

    bounds_segments = grid_bounds_segments(N)

    azim = -60.0
    empty_counter = 0
    surface_counter = 0
    n_frames = 0
    t_start = time.time()

    total_cubes = (N - 1) ** 3
    done_cubes = 0

    def render_frame(active_corner_pos=None, active_corner_val=None, azim_step=None):
        nonlocal azim, n_frames
        ax.clear()
        ax.set_facecolor(BG_COLOR)
        # 3D axes panes default to a light fill even with axis lines off;
        # force them transparent so the dark figure background shows through.
        ax.xaxis.set_pane_color((0, 0, 0, 0))
        ax.yaxis.set_pane_color((0, 0, 0, 0))
        ax.zaxis.set_pane_color((0, 0, 0, 0))
        ax.set_xlim(0, N); ax.set_ylim(0, N); ax.set_zlim(0, N)
        ax.set_box_aspect((1, 1, 1))
        ax.set_axis_off()
        azim += rotate_per_frame if azim_step is None else azim_step
        ax.view_init(elev=22, azim=azim)

        # Grid bounding cube — always shown, so you can see the volume
        # being scanned, not just the surface that's emerged from it.
        # NOTE: drawn as 12 SEPARATE Line3DCollections (one per edge),
        # not one collection of 12 segments. matplotlib's 3D renderer
        # depth-sorts whole artists against each other using a single
        # averaged depth per artist — it does not z-test per pixel against
        # other artists. One collection spanning both near and far edges
        # gets one averaged depth, so it was always drawn either entirely
        # in front of or entirely behind the mesh. Splitting per edge lets
        # each edge get its own depth and sort correctly relative to the
        # mesh (near edges in front, far edges hidden behind it).
        for p1, p2 in bounds_segments:
            ax.add_collection3d(Line3DCollection(
                [(p1, p2)], colors=GRID_BOUNDS_COLOR, linewidths=0.8, alpha=0.6))

        if faces:
            v = np.asarray(verts)
            f = np.asarray(faces)
            tris = v[f]
            pc = Poly3DCollection(
                tris, facecolor=MESH_FACE_COLOR, edgecolor=MESH_EDGE_COLOR,
                linewidths=0.15, alpha=0.95)
            ax.add_collection3d(pc)

        if active_corner_pos is not None:
            # The single voxel currently being tested — shown for every
            # cube the algorithm visits, not just the ones with a surface
            # in them, so it reads as "scanning the whole volume."
            for p1, p2 in cube_wireframe_segments(active_corner_pos):
                ax.add_collection3d(Line3DCollection(
                    [(p1, p2)], colors=ACTIVE_CUBE_COLOR, linewidths=1.3, alpha=0.9))

        if active_corner_val is not None:
            colors = [ACTIVE_INSIDE_COLOR if v_ <= threshold else ACTIVE_OUTSIDE_COLOR
                      for v_ in active_corner_val]
            ax.scatter(*active_corner_pos.T, c=colors, s=22, depthshade=False)

        fig.canvas.draw()
        buf = np.asarray(fig.canvas.buffer_rgba())
        frame_writer.append_data(buf[:, :, :3])
        n_frames += 1

    for i in range(N - 1):
        for j in range(N - 1):
            for k in range(N - 1):
                done_cubes += 1
                corner_pos = np.array([i, j, k]) + CORNER_OFFSETS
                corner_val = grid[corner_pos[:, 0], corner_pos[:, 1], corner_pos[:, 2]]

                cubeindex = 0
                for m in range(8):
                    if corner_val[m] <= threshold:
                        cubeindex |= (1 << m)

                edges = EDGE_TABLE[cubeindex]

                if edges == 0:
                    # Empty cube: still show which voxel is being tested
                    # (wireframe only, no in/out dots since nothing to
                    # highlight), but at a lower frame rate than surface
                    # cubes since there are far more of them — this is
                    # what makes it visually clear every voxel gets
                    # visited, not just the ones that produce geometry.
                    empty_counter += 1
                    if empty_counter >= empty_stride:
                        empty_counter = 0
                        render_frame(corner_pos)
                    continue

                edge_vert_idx = {}
                for e in range(12):
                    if edges & (1 << e):
                        c1, c2 = EDGE_CORNERS[e]
                        p = interp_edge(
                            corner_pos[c1].astype(float), corner_pos[c2].astype(float),
                            corner_val[c1], corner_val[c2], threshold)
                        verts.append(p)
                        edge_vert_idx[e] = len(verts) - 1

                row = TRI_TABLE[cubeindex]
                m = 0
                while row[m] != -1:
                    a, b, c = row[m], row[m + 1], row[m + 2]
                    faces.append([edge_vert_idx[a], edge_vert_idx[b], edge_vert_idx[c]])
                    m += 3

                surface_counter += 1
                if surface_counter >= surface_stride:
                    surface_counter = 0
                    for _ in range(hold_frames):
                        render_frame(corner_pos, corner_val)

                if done_cubes % 200 == 0:
                    pct = 100 * done_cubes / total_cubes
                    print(f"  scanning... {pct:5.1f}%  "
                          f"({n_frames} frames so far)", end="\r")

    # Finished mesh: do one full 360 degree turntable spin so the
    # completed shape is clearly visible from all sides.
    spin_frames = max(1, int(fps * final_spin_seconds))
    spin_step = 360.0 / spin_frames
    for _ in range(spin_frames):
        render_frame(azim_step=spin_step)

    frame_writer.close()
    plt.close(fig)
    print()
    print(f"Done: {n_frames} frames, {len(faces)} faces, "
          f"{time.time() - t_start:.1f}s render time")
    print(f"Saved {out_video}")


