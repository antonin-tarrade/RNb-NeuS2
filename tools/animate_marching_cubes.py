def grid_bounds_segments(N):
    """12 line segments (as pairs of 3D points) forming the wireframe of
    the full N x N x N grid's bounding cube."""
    c = np.array([
        (0, 0, 0), (N, 0, 0), (N, N, 0), (0, N, 0),
        (0, 0, N), (N, 0, N), (N, N, N), (0, N, N),
    ])
    edges = [(0,1),(1,2),(2,3),(3,0),(4,5),(5,6),(6,7),(7,4),(0,4),(1,5),(2,6),(3,7)]
    return [(c[a], c[b]) for a, b in edges]


def cube_wireframe_segments(corner_pos):
    """Same 12-edge wireframe, but for a single voxel's 8 corner_pos
    points (in CORNER_OFFSETS order) — used to show exactly which cube
    is currently being tested, every single voxel, scanning or not."""
    return [(corner_pos[a], corner_pos[b]) for a, b in EDGE_CORNERS]


def interp_edge(p1, p2, v1, v2, iso):
    if abs(v2 - v1) < 1e-12:
        return (p1 + p2) / 2
    t = (iso - v1) / (v2 - v1)
    return p1 + t * (p2 - p1)


