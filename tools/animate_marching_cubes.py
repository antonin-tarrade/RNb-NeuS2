"""
animate_marching_cubes.py
==========================
Renders a cube-by-cube "how marching cubes works" animation straight from a
NeuS2 / RNb-NeuS2 MLP snapshot, and saves only an .mp4 (no mesh files).

WHAT THIS ACTUALLY SHOWS (and why it's the real algorithm, not a fake reveal):
    For every voxel cube in the SDF grid, marching cubes:
      1. checks each of the cube's 8 corners: inside the surface or outside?
      2. uses that 8-bit pattern to look up which edges the surface crosses
      3. emits the triangle(s) for that specific pattern (a precomputed table
         of all 256 possible in/out patterns)
    This script does exactly that, one cube at a time, in the same scan
    order the algorithm actually uses (x, then y, then z), and renders a
    frame as the mesh grows. Empty cubes (no surface inside them — most of
    the volume) are scanned quickly without a frame each; cubes that DO
    contain a piece of surface get a frame (held a couple extra frames so
    it's visible), showing the corner inside/outside test for that cube.

    The cube-corner -> triangle lookup table used here is parsed directly
    from PyMCubes' own source (the same `mcubes` package your extraction
    pipeline already depends on), so it's the same table doing the real
    work elsewhere in your project — not a hand-typed copy. It was
    cross-checked against skimage.measure.marching_cubes on a test sphere
    (identical face count and surface area).

OUTPUT: only the .mp4. Resolution is intentionally low (default 28) because
this is an explainer, not a production extraction — at low res you can
actually see individual cubes, which is the point.

REQUIREMENTS: numpy, matplotlib, imageio, imageio-ffmpeg, and pyngp
(same as your extraction script).

USAGE:
    python animate_marching_cubes.py snapshot.msgpack --res 28 --out_video video.mp4

TIP: do a fast test first --res 16 --fps 20 to check pacing/camera before
committing to a longer render.
"""

